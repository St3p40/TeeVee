#!/usr/bin/env python3
"""Generate src/portal_page_gz.h from tools/portal/page.html: the setup / remote page, gzip-compressed.

  python3 tools/gen_portal.py

The board serves the page with "Content-Encoding: gzip" (src/portal.cpp), so it stores the compressed bytes and needs no decompressor.
Run this after every edit of page.html. The header is generated: edit page.html, not the header.
"""
import gzip
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "tools", "portal", "page.html")
OUT = os.path.join(ROOT, "src", "portal_page_gz.h")


def main():
    with open(SRC, "rb") as f:
        page = f.read()
    # mtime=0 and no file name: the same page always gives the same bytes
    gz = gzip.compress(page, compresslevel=9, mtime=0)
    rows = []
    for i in range(0, len(gz), 16):
        rows.append("    " + ", ".join("0x%02x" % b for b in gz[i:i + 16]) + ",")
    with open(OUT, "w", encoding="utf8", newline="\n") as f:
        f.write("// Generated by tools/gen_portal.py from tools/portal/page.html. Do not edit.\n")
        f.write("#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n")
        f.write("// The setup / remote page, gzip-compressed (%d bytes; the page itself is %d).\n" % (len(gz), len(page)))
        f.write("inline const uint8_t PORTAL_PAGE_GZ[] = {\n")
        f.write("\n".join(rows) + "\n};\n")
        f.write("inline const size_t PORTAL_PAGE_GZ_LEN = sizeof PORTAL_PAGE_GZ;\n")
    print("wrote %s: %d bytes (page %d)" % (OUT, len(gz), len(page)))


if __name__ == "__main__":
    main()
