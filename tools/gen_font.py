#!/usr/bin/env python3
"""Generate src/core/font_data.h + src/core/font_data.cpp: anti-aliased 4-bit bitmap fonts (ASCII 32-126) from Noto Sans via ImageMagick.

  python3 tools/gen_font.py            (needs `magick` and the Noto Sans TTFs)

Noto Sans is under the SIL Open Font License 1.1; the generated bitmaps carry that license.
Each font: one shared height (rows trimmed to the ink of all glyphs), per-glyph advance width,
4 bits of coverage per pixel, two pixels per byte, each glyph starting on a byte boundary.
"""
import os
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = "/usr/share/fonts/noto"
# name, ttf, point size
FONTS = [("FONT_SMALL", "NotoSans-SemiBold.ttf", 13), ("FONT_LARGE", "NotoSans-SemiBold.ttf", 23)]
FIRST, LAST = 32, 126


def render(ttf, size, ch, tmp):
    txt = os.path.join(tmp, "c.txt")
    with open(txt, "w") as f:
        f.write(ch)
    out = os.path.join(tmp, "g.pgm")
    subprocess.run(["magick", "-background", "black", "-fill", "white", "-font", os.path.join(FONT_DIR, ttf),
                    "-pointsize", str(size), "label:@" + txt, "-depth", "8", out], check=True)
    with open(out, "rb") as f:
        data = f.read()
    # P5 header: magic, width, height, maxval, then raw bytes
    parts, pos = [], 0
    while len(parts) < 4:
        while data[pos:pos + 1].isspace():
            pos += 1
        end = pos
        while not data[end:end + 1].isspace():
            end += 1
        parts.append(data[pos:end])
        pos = end
    w, h = int(parts[1]), int(parts[2])
    pix = data[pos + 1:pos + 1 + w * h]
    return w, h, [list(pix[r * w:(r + 1) * w]) for r in range(h)]


def build(name, ttf, size, tmp):
    glyphs = []
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        if ch == " ":
            w, h, rows = render(ttf, size, "n", tmp)  # space: blank glyph, about half an "n" wide
            glyphs.append((max(2, w // 2), h, [[0] * (w // 2)] * h))
        else:
            glyphs.append(render(ttf, size, ch, tmp))
    height = glyphs[0][1]
    ink = [r for _, _, rows in glyphs for r, row in enumerate(rows) if any(v > 40 for v in row)]
    top, bottom = min(ink), max(ink) + 1
    widths, offsets, data = [], [], bytearray()
    for w, h, rows in glyphs:
        assert h == height, "glyph heights differ"
        offsets.append(len(data))
        widths.append(w)
        nib = [min(15, (v + 8) // 17) for row in rows[top:bottom] for v in row]
        if len(nib) % 2:
            nib.append(0)
        data += bytes(nib[i] << 4 | nib[i + 1] for i in range(0, len(nib), 2))
    return name, bottom - top, widths, offsets, data


def main():
    with tempfile.TemporaryDirectory() as tmp:
        fonts = [build(*f, tmp) for f in FONTS]
    note = "// Generated by tools/gen_font.py from Noto Sans (SIL Open Font License 1.1). Do not edit."
    # The header only declares the fonts; the glyph data lives in font_data.cpp so it is compiled in exactly once
    # (static arrays in a header would be duplicated into every file that draws text).
    hdr = [note, "#pragma once", "#include <stdint.h>", "",
           "struct BitmapFont {",
           "  uint8_t height, first, last;",
           "  const uint8_t* widths;    // advance per glyph",
           "  const uint16_t* offsets;  // byte offset of each glyph in data",
           "  const uint8_t* data;      // 4-bit coverage, 2 px/byte, row-major per glyph",
           "};", ""]
    src = [note, '#include "font_data.h"', ""]
    for name, h, widths, offsets, data in fonts:
        low = name.lower()
        hdr.append(f"extern const BitmapFont {name};")
        src.append(f"static const uint8_t {low}_w[] = {{{','.join(map(str, widths))}}};")
        src.append(f"static const uint16_t {low}_o[] = {{{','.join(map(str, offsets))}}};")
        src.append(f"static const uint8_t {low}_d[] = {{")
        for i in range(0, len(data), 32):
            src.append("  " + ",".join(str(b) for b in data[i:i + 32]) + ",")
        src.append("};")
        src.append(f"const BitmapFont {name} = {{{h}, {FIRST}, {LAST}, {low}_w, {low}_o, {low}_d}};")
        src.append("")
        print(f"{name}: height {h}, {len(data)} bytes")
    with open(os.path.join(ROOT, "src", "core", "font_data.h"), "w") as f:
        f.write("\n".join(hdr) + "\n")
    with open(os.path.join(ROOT, "src", "core", "font_data.cpp"), "w") as f:
        f.write("\n".join(src))


if __name__ == "__main__":
    main()
